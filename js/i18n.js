  function t(text) { return language === 'en' ? translated(String(text)) ?? text : text; }
  // 对话组件会保存 innerHTML；原文槽随组件一起保存，恢复时无需猜测英文的中文原文。
  function sourceSlot(node, key) {
    const host=key==='text'?node.parentElement:node;
    if(!host?.getAttribute)return null;
    const attribute=key==='text'?'data-i18n-texts':'data-i18n-attrs';
    const slotKey=key==='text'?String(Array.prototype.indexOf.call(host.childNodes,node)):key;
    let slots={};
    try {
      const saved=JSON.parse(host.getAttribute(attribute)||'{}');
      if(saved && typeof saved==='object' && !Array.isArray(saved))slots=saved;
    } catch { /* 旧/损坏元数据不参与恢复 */ }
    const slot=slots[slotKey];
    return {host,attribute,slotKey,slots,previous:slot && typeof slot.original==='string' && typeof slot.output==='string'?slot:null};
  }
  function saveSource(slot, value) {
    if(!slot)return;
    if(value)slot.slots[slot.slotKey]=value; else delete slot.slots[slot.slotKey];
    const serialized=JSON.stringify(slot.slots);
    if(serialized==='{}')slot.host.removeAttribute(slot.attribute);
    else if(slot.host.getAttribute(slot.attribute)!==serialized)slot.host.setAttribute(slot.attribute,serialized);
  }
  function replace(node, key, current, write) {
    let slots = records.get(node);
    const source=sourceSlot(node,key);
    const previous = slots?.[key] || source?.previous;
    const original = previous && current === previous.output ? previous.original : current;
    const trimmed = original.trim();
    const english = key==='text' && node.parentElement?.classList.contains('calendar-weekday')
      ? ({一:'Mon',二:'Tue',三:'Wed',四:'Thu',五:'Fri',六:'Sat',日:'Sun'})[trimmed] ?? null
      : translated(trimmed);
    if (english === null) { if (slots) delete slots[key]; saveSource(source,null); return; }
    const output = language === 'en' ? original.replace(trimmed, english) : original;
    if (!slots) { slots = {}; records.set(node, slots); }
    slots[key] = {original, output};
    saveSource(source,slots[key]);
    if (current !== output) write(output);
  }
  function excludedNode(node) {
    // 文本框内容属于用户；框本身的提示语和可访问性标签仍需本地化。
    const textarea=node.parentElement?.closest('textarea');
    if(textarea)return textarea;
    const boundary=node.nodeType === 1 ? node.closest(excluded) : node.parentElement?.closest(excluded);
    // 卡片种类是界面标签；网络名与尾号保持原样。其他对象名称仍保留原文。
    if(boundary?.matches('.account-object-identity > strong') && /^(信用卡|借记卡|Credit card|Debit card) · .+ \d{4}$/.test(boundary.textContent))return null;
    return boundary;
  }
  function applyNode(node) {
    if (node.nodeType === 3) replace(node, 'text', node.nodeValue, value=>{node.nodeValue=value;});
    else if (node.nodeType === 1) for (const attr of ['title','placeholder','aria-label','data-label']) {
      if (node.hasAttribute(attr)) replace(node, attr, node.getAttribute(attr), value=>node.setAttribute(attr,value));
    }
  }
  function apply(root = document.body) {
    if (!root || excludedNode(root)) return;
    // 也处理根节点和尚未挂载的组件；输入值、原始资料与用户内容不改写。
    applyNode(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (excludedNode(node)) return NodeFilter.FILTER_REJECT;
        if (node.nodeType === 3 && !node.textContent.trim()) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    for (let node = walker.nextNode(); node; node = walker.nextNode()) applyNode(node);
  }
  function setText(element, text) {
    element.textContent = String(text ?? '');
    apply(element);
    return element;
  }
