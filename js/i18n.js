    queueMicrotask(sync);
    new MutationObserver(mutations=> {
      // 微任务内处理新增/重写的局部内容，在浏览器绘制前完成，不等待下一帧全页替换。
      const roots = new Set();
      for (const mutation of mutations) {
        const root = mutation.type === 'characterData' ? mutation.target.parentElement : mutation.target;
        if (root?.isConnected && !excludedNode(root)) roots.add(root);
      }
      for (const root of roots) {
        if (![...roots].some(other=>other!==root && other.contains(root))) apply(root);
      }
    }).observe(document.body, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['title','placeholder','aria-label','data-label']});
